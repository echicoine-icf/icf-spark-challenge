# Canonical normalized tokens only; no individual dbGaP metadata is exported.
CONCEPTS = tuple(sorted({
    {'triglycerides':'triglyceride','haemoglobin':'hemoglobin',
     'glycated hemoglobin':'hemoglobin','hba1c':'hemoglobin'}.get(t,t)
    for t in adaptive.TERM_WHITELIST
}))
APPROVED = frozenset((source, template.format(concept=term))
    for term in CONCEPTS for role in TEMPLATES.values()
    for source, templates in role.items() for template in templates)
TEMPLATE_SHA256 = hashlib.sha256(json.dumps(TEMPLATES,sort_keys=True).encode()).hexdigest()


def choose_concept(row:dict) -> str|None:
    """Prefer explicit analyte in the field name over contextual mentions in description."""
    name=re.sub(r'(?<=[a-z0-9])(?=[A-Z])',' ',str(row.get('variable_name') or '')).casefold().replace('_',' ')
    canonical={'triglycerides':'triglyceride','haemoglobin':'hemoglobin',
               'glycated hemoglobin':'hemoglobin','hba1c':'hemoglobin'}
    for term in sorted(adaptive.TERM_WHITELIST,key=lambda x:(-len(x),x)):
        if re.search(r'(?<!\w)'+re.escape(term)+r'(?!\w)',name):
            return canonical.get(term,term)
    compact_name=re.sub(r'[^a-z0-9]','',name)
    # Common compound names in dbGaP dictionaries (e.g. fastinsulin).
    for embedded in ('insulin','glucose','creatinine','cholesterol','hemoglobin','bilirubin'):
        if embedded in compact_name:
            return embedded
    return adaptive.choose_term(row)


def detect_role(row:dict) -> str:
    """Select SEARCH intent only, based on structural cues, never on gold labels."""
    name = re.sub(r'(?<=[a-z0-9])(?=[A-Z])',' ',str(row.get('variable_name') or '')).replace('_',' ')
    desc = str(row.get('variable_description') or '')
    content = (name + ' ' + desc).casefold()
    if re.search(r'not\s*done|not\s*performed|not\s*measured|test\s*(?:status|completed)|not\s*taken',content) or re.search(r'(?:ogtt|glucose)(?:test)?done$',name.replace(' ','').casefold()):
        return 'test_status'
    if (re.search(r'\bunits?\b|\bunit\s*of\b',name.casefold()) or
        re.search(r'(?:si)?units?$',re.sub(r'[^a-z]','',name.casefold())) or
        re.search(r'^(?:glucose\s+)?units?(?:\s*\[|$)',desc.casefold())):
        return 'result_units'
    if re.search(r'diet(?:ary)?\b|nutrients?\b|food\b|intake\b|nutrition\b|consumption\b',content):
        return 'dietary_quantity'
    if re.search(r'age\s*(?:at|in\s*years)|date\s*(?:of|at)|time\s*(?:of|since)',name.casefold()):
        return 'timing_metadata'
    if re.search(r'method\s+of\s+data\s+collection|collection\s+method|specimen\s+collection\s+method',content):
        return 'collection_method'
    if re.search(r'\bpet\b|\bpetincr\b|\bmetabolism\b|positron\s+emission|\bfdg\b|\bimaging\b',content):
        return 'imaging_descriptor'
    if re.search(r'impaired\s+\w+\s+tolerance|\bdiagnos(?:is|tic)\b|\bsyndrome\b',content):
        return 'derived_diagnosis'
    if re.search(r'\bcase\s+group\b|\bcase\s+status\b|\bcase\s+control\b|included\s+in\b|\bflag\b',content):
        return 'case_indicator'
    if re.search(r'\binfusion\b|\bdos(?:e|age|ing)\b|\badminist(?:ered|ration)\b|\bprophylact',content):
        return 'administration'
    if re.search(r'urinalysis|\burin(?:e|ary)\b',content):
        return 'urine_observation'
    if re.search(r'\bfasting\b|\bserum\b|\bplasma\b|\bblood\b',content):
        return 'blood_observation'
    return 'general'


def plan_queries(row:dict, sources:tuple[str,...]) -> tuple[str|None,str,list[dict]]:
    """Return concept, role hint, unique bounded source/query pairs."""
    concept = choose_concept(row)
    role = detect_role(row)
    if not concept: return None, role, []
    assert concept in CONCEPTS
    result=[]
    for source in sources:
        for template in TEMPLATES[role].get(source, ())[:2]:
            query=template.format(concept=concept)
            assert (source,query) in APPROVED
            result.append({'source':source,'query':query,'intent':role})
    return concept,role,result[:8]


def plan_preview(batch:Path, per_class:int,sources:tuple[str,...]):
    import spark_llm_experiment as prior
    raw=json.loads(batch.read_text(encoding='utf-8'))
    prior.validate_batch(raw)
    rows=prior.select_rows(raw,per_class)
    pairs=set();intents=Counter()
    for row in rows:
        concept,role,planned=plan_queries(row,sources)
        intents[role]+=1
        for p in planned:pairs.add((p['source'],p['query']))
        print(f"{row['variable_id']} [{role}] -> " +
              (', '.join(p['source']+':'+p['query'] for p in planned) or 'no approved lookup'))
    print('PREVIEW ONLY:',json.dumps({'rows':len(rows),'unique_query_pairs':len(pairs),
                                     'roles':dict(intents),'template_sha256':TEMPLATE_SHA256},sort_keys=True))


def safe_fetch(source:str,query:str,*,api_key:str|None=None,timeout:int=12)->dict:
    """Fetch allowlisted template query; no redirects or arbitrary URLs permitted."""
    if (source,query) not in APPROVED:
        raise ValueError('Only approved source and contextual query template are permitted')
    if source == 'umls' and not api_key:
        raise ValueError('UMLS_API_KEY is required when source=umls')
    endpoint=prior_multi.ENDPOINTS[source]
    if source=='evs':
        params={'term':query,'pageSize':5,'type':'phrase' if ' ' in query else 'match','include':'minimal'}
    elif source=='nlm_loinc':
        params={'terms':query,'count':5,'type':'question','df':'text,LOINC_NUM','excludeCopyrighted':'true'}
    elif source=='nlm_disease':
        params={'terms':query,'count':5,'df':'DiseaseName','cf':'ConceptID'}
    else:
        params={'string':query,'searchType':'normalizedWords' if ' ' in query else 'exact',
                'pageSize':5,'apiKey':api_key}
    url=endpoint+'?'+urlencode(params)
    req=Request(url,headers={'User-Agent':'ICF-SPARK-5H7-development-enrichment/1.0',
                             'Accept':'application/json'})
    class NoRedirect(HTTPRedirectHandler):
        def redirect_request(self, req, fp, code, msg, headers, newurl):return None
    with build_opener(NoRedirect()).open(req,timeout=timeout) as response:
        if response.geturl().split('?',1)[0]!=endpoint:
            raise ValueError('Unexpected API endpoint or redirect')
        if response.status!=200:raise ValueError('Unexpected HTTP status')
        data=response.read(prior_multi.MAX_RESPONSE_BYTES+1)
        if len(data)>prior_multi.MAX_RESPONSE_BYTES:
            raise ValueError('Response exceeds 256 KiB')
    doc=json.loads(data.decode('utf-8'))
    if source=='evs':
        if not isinstance(doc,dict) or not isinstance(doc.get('concepts'),list):
            raise ValueError('Unexpected NCI EVS response')
        concepts=[]
        for c in doc['concepts'][:5]:
            if not isinstance(c,dict):continue
            code=c.get('code');name=prior_multi.clean_name(c.get('name'))
            if isinstance(code,str) and re.fullmatch(r'C\d{3,10}',code) and name:
                concepts.append({'id':'NCIT:'+code,'name':name})
    elif source=='umls':
        concepts=prior_multi.parse_umls(doc)
    else:
        concepts=prior_multi.parse_clinicaltables(doc,source)
    return {'source':source,'api':endpoint,'query':query,'search_only':True,
        'not_a_variable_label':True,'concepts':concepts,
        'response_sha256':hashlib.sha256(data).hexdigest(),
        'query_template_version':VERSION}
